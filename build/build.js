#!/usr/bin/env node
/* build/build.js : concatenates src/ into a single self-contained team-connect.html (no dependencies).
   Also writes dev.html, which loads the same files individually for debugging. */
const fs = require("fs"), path = require("path");
const root = path.resolve(__dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "src/manifest.json"), "utf8"));
const read = f => fs.readFileSync(path.join(root, f), "utf8");
const css = manifest.styles.map(f => `/* ==== ${f} ==== */\n` + read(f)).join("\n\n");
const js = manifest.scripts.map(f => `/* ==== ${f} ==== */\n` + read(f)).join("\n\n");
if (/<\/script/i.test(js)) { console.error("Refusing to build: a script contains </script>"); process.exit(1); }
const head = `<!-- team-connect.html · TEAM CONNECT LIVE · single-file build ${new Date().toISOString().slice(0, 10)} · generated by build/build.js from src/ -->
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="color-scheme" content="dark">
<title>TEAM CONNECT LIVE</title>
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E%3Crect width='64' height='64' rx='14' fill='%2307080f'/%3E%3Ccircle cx='32' cy='32' r='14' fill='none' stroke='%23e8b84b' stroke-width='6'/%3E%3C/svg%3E">
<!-- Fonts are an optional enhancement: the app renders with system fonts when offline. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400..700&family=Schibsted+Grotesk:wght@400..600&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet" media="print" onload="this.media='all'">
<style>
`;
const single = head + css + `\n</style>\n</head>\n<body>\n<div id="app" aria-live="polite"></div>\n<script>\n` + js + `\n</script>\n</body>\n</html>\n`;
fs.writeFileSync(path.join(root, "team-connect.html"), single);
const dev = head.replace("<style>\n", "") + manifest.styles.map(f => `<link rel="stylesheet" href="${f}">`).join("\n") + `\n</head>\n<body>\n<div id="app" aria-live="polite"></div>\n` + manifest.scripts.map(f => `<script src="${f}"></script>`).join("\n") + `\n</body>\n</html>\n`;
fs.writeFileSync(path.join(root, "dev.html"), dev);
console.log(`built team-connect.html (${(single.length / 1024).toFixed(0)} KB) and dev.html`);
